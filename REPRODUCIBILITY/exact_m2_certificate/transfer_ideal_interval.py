"""Exact m=2 orthogonal bath computer-assisted BKM continuum interval, bounded for one point.
Uses prior DD bound for same C++ process, plus independently certified <4e-27
for exact polynomial versus stored high-precision coefficients.
The BKM Darboux bounds are generated by certified_BKM_tight.py.
"""
from pathlib import Path
import mpmath as m
m.iv.dps=70;I=m.iv.mpf
p=(Path(__file__).resolve().parent / 'out_ideal_m2_lean.txt')
R=[[I(z) for z in line.split()] for line in p.read_text().splitlines()];assert len(R)==4
v=lambda j:(R[j][0]+R[j][1],R[j][2]+R[j][3]);V=[[v(0),v(2)],[v(1),v(3)]]
abs2=lambda z:z[0]*z[0]+z[1]*z[1]
prod=lambda a,b:(a[0]*b[0]-a[1]*b[1],a[0]*b[1]+a[1]*b[0])
sub=lambda a,b:(a[0]-b[0],a[1]-b[1])
det=sub(prod(V[0][0],V[1][1]),prod(V[0][1],V[1][0]))
s=I('.2')*sum((abs2(V[i][j]) for i in range(2) for j in range(2)),I(0));a=1-s
d=I('.04')*abs2(det);sig_lower=m.iv.sqrt(I(5)*d/s)
# These bounds round OUTWARD relative to the computed Darboux sums.
L=I('3.9670526841476009e-41');U=I('3.9710197867922034e-41')
E=I('1.2e-22');delta=E/sig_lower
assert delta.b < I('.002').a
am=(1-delta)**2;ap=(1+delta)**2
cm=a/(1-am*s);cp=a/(1-ap*s);kappa=I('.05')/a
phi=lambda z:z*z*(1-kappa)/(1-z*kappa)
faclo=am*phi(cm);fachi=ap*phi(cp)
assert (1-ap*s).a>0 and (1-cp*kappa).a>0
print('singular_value_lower',sig_lower.a)
print('delta_upper',delta.b)
print('BKM_discrete_matrix_lower',L.a)
print('BKM_discrete_matrix_upper',U.b)
print('BKM_continuum_exact_orthogonal_lower', (L*faclo).a)
print('BKM_continuum_exact_orthogonal_upper', (U*fachi).b)
print('SCOPE: exact m=2 point only; computational hypotheses detailed in README_REPRODUCE.md')
